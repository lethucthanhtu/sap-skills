/**
 * Turn `evals/triggers.json` into `claude plugin eval` case files.
 *
 * Why a generator: trigger evals are one prompt + one expected skill each, and keeping
 * 30 near-identical `case.yaml` files in sync by hand is how graders drift. The JSON is
 * the single source of truth; the YAML is generated and checked for drift by
 * `npm run validate`, so CI fails if someone edits one without the other.
 * @module evals
 */

/**
 * Regex the `tool_used` grader matches against the JSON-encoded Skill tool input.
 * Accepts the plugin-namespaced form (`sap:sap`) as well as the bare name.
 * @param {string} skill
 * @returns {string}
 */
export function skillInputMatch(skill) {
  return `"skill"\\s*:\\s*"(?:[\\w-]+:)?${skill}"`;
}

/**
 * Render one case.yaml. JSON.stringify gives valid YAML double-quoted scalars, which keeps
 * arbitrary prompt text (colons, quotes, backticks) safe without a YAML library.
 * @param {{ id: string, prompt: string, expect: string | null, note?: string }} c
 * @param {string[]} allSkills Every model-invocable skill in the plugin, so negative cases can forbid all of them.
 * @returns {string}
 */
export function renderCase(c, allSkills) {
  const positive = c.expect !== null;
  const lines = [
    '# GENERATED by scripts/gen-evals.mjs from evals/triggers.json — edit that file, then run `npm run evals:gen`.',
    'schema_version: "1.1"',
    `name: ${JSON.stringify(`trigger-${c.id}`)}`,
    `description: ${JSON.stringify(c.note ?? (positive ? `should trigger ${c.expect}` : 'must not trigger any SAP skill'))}`,
    `tags: [trigger, ${positive ? 'positive' : 'negative'}]`,
    'runs: 1',
    'execution:',
    `  prompt: ${JSON.stringify(c.prompt)}`,
    '  max_turns: 8',
    '  timeout_seconds: 240',
    '  allowed_tools: [Read, Glob, Grep, Skill]',
    'graders:',
  ];
  if (positive) {
    lines.push(
      '  - name: skill-fired',
      '    type: tool_used',
      '    tool: Skill',
      `    input_match: ${JSON.stringify(skillInputMatch(c.expect))}`,
      '  - name: states-environment-or-asks',
      '    type: regex',
      '    target: last_message',
      '    flags: i',
      `    pattern: ${JSON.stringify('ECC|S/4HANA|BTP|ABAP Cloud|on-premise|environment|release|CAP|UI5|Fiori|HANA|MDG')}`,
    );
  } else {
    lines.push(
      '  - name: no-sap-skill',
      '    type: tool_used',
      '    tool: Skill',
      `    input_match: ${JSON.stringify(`"skill"\\s*:\\s*"(?:[\\w-]+:)?(?:${allSkills.join('|')})"`)}`,
      '    min: 0',
      '    max: 0',
      '    arm: both',
    );
  }
  return `${lines.join('\n')}\n`;
}

/**
 * Map every trigger case to the file it should generate.
 * @param {{ id: string, prompt: string, expect: string | null, note?: string }[]} cases
 * @param {string[]} allSkills
 * @returns {Map<string, string>} relative path → contents
 */
export function renderAll(cases, allSkills) {
  const files = new Map();
  for (const c of cases) files.set(`evals/triggers/${c.id}/case.yaml`, renderCase(c, allSkills));
  return files;
}
